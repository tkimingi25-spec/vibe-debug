import json
import os

from vibe_debug.runtime.static_analyzer import StaticPipelineMap


def generate_config(
    pipeline_map: StaticPipelineMap,
    project_root: str,
    project_name: str = None,
    output_path: str = None
):
    """
    Auto-generate vibedebug.toml from static analysis results.
    Never overwrites user edits - only updates discovered sections.
    """
    config_path = output_path or os.path.join(
        project_root, "vibedebug.toml"
    )

    if not project_name:
        project_name = os.path.basename(project_root)

    watch_modules = [
        m for m in pipeline_map.modules
        if not m.startswith("test")
        and "__" not in m
        and "setup" not in m
    ]

    entry_points_str = "\n".join(
        [f'  "{ep}"' for ep in pipeline_map.entry_points[:5]]
    ) or '  "unknown - no main.py or app.py detected"'

    modules_str = "\n".join(
        [f'  "{m}",' for m in watch_modules]
    )

    config_content = f"""# AUTO-GENERATED by vibe-debug static analyzer
# Edit to customize - delete to regenerate on next start
# Generated from: {project_root}

[project]
name = "{project_name}"

[tracer]
otlp_endpoint = "http://localhost:6006/v1/traces"

[discovered_components]
# vibe-debug found these by reading your source files
total_functions = {len(pipeline_map.functions)}
total_modules = {len(pipeline_map.modules)}
entry_points = [
{entry_points_str}
]

[watch]
# Auto-populated from static analysis - edit to add/remove modules
modules = [
{modules_str}
]

[thresholds]
# Flag function calls slower than this as performance warnings
slow_call_ms = 500
# Flag empty returns from these component types as silent failures
silent_failure_types = ["rag", "router", "agent", "knowledge_graph"]

[adapters]
# Optional deep-context plugins - remove any you don't use
enabled = ["ollama", "langchain", "openai"]
"""

    with open(config_path, "w") as f:
        f.write(config_content)

    print(f"[vibe-debug] Config generated: {config_path}")
    print(
        f"[vibe-debug] Discovered {len(pipeline_map.functions)} "
        f"functions in {len(pipeline_map.modules)} modules"
    )
    return config_path
